def upload_to_huggingface(data_dir):
    """Upload dataset to HuggingFace Hub."""
    try:
        from huggingface_hub import HfApi
    except ImportError:
        print("ERROR: huggingface_hub not installed. Run: pip install huggingface_hub")
        print("Then: huggingface-cli login")
        return False

    api = HfApi()
    repo_id = "Taurus-Ai-Corp/gcfd-synthetic-eeg"

    print(f"\nUploading to HuggingFace: {repo_id}")
    api.create_repo(repo_id, repo_type="dataset", exist_ok=True)
    api.upload_folder(
        folder_path=data_dir,
        repo_id=repo_id,
        repo_type="dataset",
        commit_message="Upload synthetic EEG datasets for 7 clinical conditions"
    )
    print(f"Upload complete: https://huggingface.co/datasets/{repo_id}")
    return True


