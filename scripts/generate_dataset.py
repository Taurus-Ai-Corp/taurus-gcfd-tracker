DURATION = 10  # seconds
FS = 250  # Hz
THETA_BAND = (4, 8)
GAMMA_BAND = (30, 100)


def generate_all_datasets(output_dir):
    """Generate CSV datasets for all clinical presets."""
    os.makedirs(output_dir, exist_ok=True)

    metadata = {
        "dataset_name": "gcfd-synthetic-eeg",
        "title": "Bio-Quantum Eigenmodes: Healthy Brainwave Signatures for Therapeutic Entrainment",
        "description": (
            "Synthetic EEG datasets generated by taurus-gcfd-tracker for 7 clinical conditions. "
            "Each file contains a 10-second single-channel EEG signal at 250 Hz with theta-gamma "
            "phase-amplitude coupling, plus bandpass-filtered components and instantaneous phases."
        ),
        "generator": "taurus-gcfd-tracker v1.0.0",
        "sampling_rate_hz": FS,
        "duration_sec": DURATION,
        "theta_band_hz": list(THETA_BAND),
        "gamma_band_hz": list(GAMMA_BAND),
        "license": "Apache-2.0",
        "presets": {}
    }

    for key, preset in CLINICAL_PRESETS.items():
        print(f"Generating: {preset['label']} ({key}.csv)...")

        t, channels = generate_synthetic_eeg(
            duration=DURATION, fs=FS,
            theta_amp=preset["theta_amp"],
            gamma_amp=preset["gamma_amp"],
            noise_level=preset["noise"],
            seed=preset["seed"]
        )
        eeg = channels[0]

        # Compute filtered components and phases
        theta_filtered = bandpass_filter(eeg, THETA_BAND[0], THETA_BAND[1], FS)
        gamma_filtered = bandpass_filter(eeg, GAMMA_BAND[0], GAMMA_BAND[1], FS)
        theta_phase = extract_phase(eeg, THETA_BAND[0], THETA_BAND[1], FS)
        gamma_phase = extract_phase(eeg, GAMMA_BAND[0], GAMMA_BAND[1], FS)

        # Compute PLV
        phase_diff = theta_phase - gamma_phase
        plv = float(np.abs(np.mean(np.exp(1j * phase_diff))))
        coherence_score = 0.5 + (plv * 0.5)

        # Write CSV
        csv_path = os.path.join(output_dir, f"{key}.csv")
        with open(csv_path, 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(["time_s", "eeg_uv", "theta_filtered", "gamma_filtered",
                             "theta_phase_rad", "gamma_phase_rad"])
            for i in range(len(t)):
                writer.writerow([
                    f"{t[i]:.6f}",
                    f"{eeg[i]:.6f}",
                    f"{theta_filtered[i]:.6f}",
                    f"{gamma_filtered[i]:.6f}",
                    f"{theta_phase[i]:.6f}",
                    f"{gamma_phase[i]:.6f}"
                ])

        # Record metadata
        metadata["presets"][key] = {
            "label": preset["label"],
            "file": f"{key}.csv",
            "theta_amp": preset["theta_amp"],
            "gamma_amp": preset["gamma_amp"],
            "noise_level": preset["noise"],
            "seed": preset["seed"],
            "expected_score_range": preset["expected_score"],
            "computed_plv": round(plv, 4),
            "computed_coherence_score": round(coherence_score, 4),
            "citation": preset["citation"],
            "n_samples": len(t)
        }

        print(f"  PLV={plv:.4f}  Coherence={coherence_score:.4f}  (expected: {preset['expected_score']})")

    # Write metadata
    meta_path = os.path.join(output_dir, "metadata.json")
    with open(meta_path, 'w') as f:
        json.dump(metadata, f, indent=2)
    print(f"\nMetadata written to {meta_path}")

    # Write dataset card (README.md for HuggingFace)
    readme_path = os.path.join(output_dir, "README.md")
    with open(readme_path, 'w') as f:
        f.write(DATASET_CARD)
    print(f"Dataset card written to {readme_path}")

    return metadata


